"""Generate web/src/starfield.css: three parallax layers of stars drifting upwards, pure CSS.

Each layer is one empty element whose stars are box-shadows placed in vw/vh; its ::after repeats the same
stars one screen lower, so translating the layer by -100vh loops without a seam. Only transform animates
(GPU), the shadows are rasterised once. Deterministic: run again to get the same file.
"""

import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "web" / "src" / "starfield.css"
LAYERS = [  # (class, size px, stars per screen, seconds per loop)
    ("stars-s", 1.5, 110, 90),
    ("stars-m", 2.5, 45, 60),
    ("stars-l", 3.5, 18, 40),
]
rnd = random.Random(2026)


def color() -> str:
    if rnd.random() < 0.35:
        return f"rgba(52, 211, 153, {rnd.uniform(0.4, 0.6):.2f})"
    return f"rgba(255, 255, 255, {rnd.uniform(0.3, 0.5):.2f})"


css = ['''/* Generated by scripts/make_starfield.py — do not edit by hand. */
.starfield {
  position: fixed; inset: 0; z-index: 0; pointer-events: none; overflow: hidden;
  background: radial-gradient(circle at 50% 45%, #11241b 0%, #090c0b 65%, #050706 100%);
}
.starfield > div { position: absolute; left: 0; top: 0; border-radius: 50%; background: transparent;
  will-change: transform; transform: translate3d(0, 0, 0); animation: star-rise linear infinite; }
.starfield > div::after { content: ""; position: absolute; left: 0; top: 100vh; width: inherit; height: inherit;
  border-radius: 50%; box-shadow: inherit; }
@keyframes star-rise { from { transform: translate3d(0, 0, 0) } to { transform: translate3d(0, -100vh, 0) } }
@media (prefers-reduced-motion: reduce) { .starfield > div { animation: none; } }''']
for cls, size, n, secs in LAYERS:
    shadows = ", ".join(f"{rnd.uniform(0, 100):.2f}vw {rnd.uniform(0, 100):.2f}vh {color()}" for _ in range(n))
    css.append(f".starfield > .{cls} {{ width: {size}px; height: {size}px; animation-duration: {secs}s; box-shadow: {shadows}; }}")
OUT.write_text("\n".join(css) + "\n")
print(OUT, sum(n for *_, n, _ in LAYERS), "stars")
